export const DATA_TOOLS: DataTool[] = DATA_CONTENT.map((content) => {
  const config = CONFIG[content.slug];
  if (!config) throw new Error(`Falta configuración de la herramienta de datos: ${content.slug}`);
  return { ...content, ...config };
});

export function getDataTool(slug: string): DataTool | undefined {
  return DATA_TOOLS.find((tool) => tool.slug === slug);
}

export const DATA_TOOL_PATHS = DATA_TOOLS.map((tool) => `/convertir/${tool.slug}`);
